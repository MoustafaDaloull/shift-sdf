<?php

declare(strict_types=1);

namespace App\Shared\Support;

use Illuminate\Support\Str;

/**
 * معرّف التتبع الفريد للطلب الواحد — `API-021` · `EP-OBS-004`.
 *
 * يُربط في الحاوية بـ`scoped` فيُولَّد مرة واحدة لكل طلب، ويقرأه المُصيِّر
 * والوسيط والسجل من المثيل نفسه. ولولا ذلك لأمكن أن تحمل الترويسة معرّفًا
 * وتحمل الاستجابة غيره، فينقطع الخيط الذي وُضع المعرّف أصلًا لوصله.
 *
 * ── `scoped` لا `singleton` ──────────────────────────────────────────────
 * `singleton` يعمل صحيحًا تحت PHP-FPM — حيث تموت العملية مع الطلب — ثم يحمل
 * كل طلبات العامل الواحد المعرّف نفسه لحظة تشغيل Octane. و`scoped` يُعاد
 * ضبطه بين الطلبات في الحالتين. التسجيل في `AppServiceProvider::register`.
 *
 * ── لماذا UUID لا `req_abc123` ───────────────────────────────────────────
 * `API-021` يضرب `req_abc123` مثالًا ولا يفرض صيغة. والقيد الفعلي من جهة
 * أخرى: عمود `correlation_id` في سجل التدقيق `VARCHAR(36)` — وهو طول UUID
 * تمامًا. فأي بادئة تُضاف تدفع المعرّف خارج العمود الذي سيحمله، ويظهر ذلك
 * عند أول كتابة في السجل لا عند كتابة هذا السطر.
 *
 * ── ولماذا لا يُقبل معرّف من العميل ──────────────────────────────────────
 * `API-021` ينصّ على أنه «يُولد من الخادم». وقبول ترويسة واردة يجعل نصًّا
 * يتحكم به الطالب يدخل السجلّ ويُلوّثه.
 */
final class TraceContext
{
    private ?string $id = null;

    public function id(): string
    {
        return $this->id ??= Str::uuid()->toString();
    }
}
